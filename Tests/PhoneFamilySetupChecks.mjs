import assert from 'node:assert/strict';
import {newCloudFamily} from '../download-site/public/app/family-setup.mjs';
import {phoneView} from '../download-site/public/app/cloud.mjs';
const input={user:{id:crypto.randomUUID(),email:'test@example.invalid'},name:' Test crew ',parentName:'Parent',childName:'Child',timezone:'America/Los_Angeles',locale:'en-US'};
const snapshot=newCloudFamily(input,new Date('2026-10-07T17:00:00Z'));
assert.equal(snapshot.family.name,'Test crew');
assert.equal(snapshot.users[0].id,input.user.id);
assert.equal(snapshot.members[0].role,'guardian');
assert.equal(snapshot.jars.length,3);
assert.equal(snapshot.schedule.frequency,'weekly');
assert.equal(snapshot.schedule.nextPaydayAt,'2026-10-14T17:00:00.000Z');
const view=phoneView({revision:1,state:snapshot});
assert.equal(view.cloud,true);assert.equal(view.children[0].name,'Child');
assert.deepEqual(view.children[0].split,{spend:50,save:40,give:10});
assert.equal(view.work.length,0);assert.equal(view.ledger.length,0);
assert.ok(!JSON.stringify(snapshot).includes('passcode'));
assert.throws(()=>newCloudFamily({...input,user:null}),/Sign in/);
assert.throws(()=>newCloudFamily({...input,childName:''}),/nickname/);
assert.throws(()=>newCloudFamily({...input,currency:'BAD'}),/currency/);
console.log('Phone-first cloud family: schema, ownership, empty ledger, validation and phone adapter passed.');
