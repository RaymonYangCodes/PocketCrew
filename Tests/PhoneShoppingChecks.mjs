import assert from 'node:assert/strict';
import {demo,balance} from '../download-site/public/app/domain.mjs';
import {applyLocalShopping,photoURL,shoppingSamples} from '../download-site/public/app/shopping-domain.mjs';
const s=demo(),product=shoppingSamples[0];
applyLocalShopping(s,'jordan','add',{product,childId:'jordan',destination:'wishlist'});
const entry=s.shoppingEntries[0];
assert.throws(()=>applyLocalShopping(s,'riley','cart',{id:entry.id}),/own list/);
assert.throws(()=>applyLocalShopping(s,'jordan','price',{id:entry.id,priceCents:1,reason:'x'}),/parent/);
assert.throws(()=>applyLocalShopping(s,'jordan','gift',{id:entry.id}),/parent/);
applyLocalShopping(s,'jordan','goal',{id:entry.id,childId:'jordan',title:product.title,target:product.priceCents});
assert.equal(s.goals.at(-1).status,'proposed');assert.deepEqual(s.goals.at(-1).shoppingProduct,product);
const goal=s.goals.at(-1);applyLocalShopping(s,'parent','reviewGoal',{id:goal.id,decision:'active'});assert.equal(goal.status,'active');
applyLocalShopping(s,'jordan','cart',{id:entry.id});
const before=balance(s,'jordan','spend');
applyLocalShopping(s,'parent','price',{id:entry.id,priceCents:101,reason:'Contribution'});
assert.equal(balance(s,'jordan','spend'),before);
applyLocalShopping(s,'parent','approve',{id:entry.id,expectedPrice:101});assert.equal(balance(s,'jordan','spend'),before-101);
assert.throws(()=>applyLocalShopping(s,'parent','approve',{id:entry.id}),/pending/);
assert.throws(()=>applyLocalShopping(s,'parent','price',{id:entry.id,priceCents:200,reason:'x'}),/pending/);
assert.equal(photoURL('https://tracker.example/child'),null);assert.equal(photoURL('javascript:alert(1)'),null);
assert.ok(photoURL('https://encrypted-tbn0.gstatic.com/product.png'));
console.log('Phone shopping: own-child isolation, parent-only prices/gifts, goal metadata, approvals, exact cents, history immutability and photo allowlist passed.');
